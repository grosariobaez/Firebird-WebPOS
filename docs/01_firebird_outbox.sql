/*
  JOMLIA -> webpos_rd | FASE 1: Cola transaccional de facturas
  Requiere Firebird 2.1+ (UPDATE OR INSERT ... MATCHING).
  EJECUTAR SOLO TRAS BACKUP Y PRUEBAS EN UNA COPIA DE LA BD.
  No ejecuta consultas remotas ni modifica datos comerciales existentes.
*/

CREATE TABLE PA_FB_OUTBOX (
  IDCOMPANIA INTEGER NOT NULL,
  IDFACTURA INTEGER NOT NULL,
  ESTADO VARCHAR(1) DEFAULT 'P' NOT NULL,
  INTENTOS INTEGER DEFAULT 0 NOT NULL,
  FECHA_EVENTO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  FECHA_PROCESADO TIMESTAMP,
  PROXIMO_INTENTO TIMESTAMP,
  ULTIMO_ERROR VARCHAR(500),
  CONSTRAINT PK_PA_FB_OUTBOX PRIMARY KEY (IDCOMPANIA, IDFACTURA),
  CONSTRAINT CK_PA_FB_OUTBOX_EST CHECK (ESTADO IN ('P','R','S','E'))
);

CREATE INDEX IDX_PA_FB_OUTBOX_EST ON PA_FB_OUTBOX (ESTADO, PROXIMO_INTENTO);

SET TERM ^ ;

CREATE PROCEDURE PA_ENCOLAR_FACTURA (
  P_IDCOMPANIA INTEGER,
  P_IDFACTURA INTEGER
)
AS
BEGIN
  /* Una fila por factura: el trigger puede dispararse por varios pagos. */
  UPDATE OR INSERT INTO PA_FB_OUTBOX (
    IDCOMPANIA, IDFACTURA, ESTADO, INTENTOS,
    FECHA_EVENTO, FECHA_PROCESADO, PROXIMO_INTENTO, ULTIMO_ERROR
  ) VALUES (
    :P_IDCOMPANIA, :P_IDFACTURA, 'P', 0,
    CURRENT_TIMESTAMP, NULL, NULL, NULL
  )
  MATCHING (IDCOMPANIA, IDFACTURA);
END^

CREATE TRIGGER PA_TR_FPA_EMI_INS FOR FORMAS_PAGO
ACTIVE AFTER INSERT POSITION 100
AS
BEGIN
  IF (NEW.FPA_STATUS = 'EMI') THEN
    EXECUTE PROCEDURE PA_ENCOLAR_FACTURA(NEW.IDCOMPANIA, NEW.IDFACTURA);
END^

CREATE TRIGGER PA_TR_FPA_EMI_UPD FOR FORMAS_PAGO
ACTIVE AFTER UPDATE POSITION 100
AS
BEGIN
  IF (NEW.FPA_STATUS = 'EMI' AND
      (OLD.FPA_STATUS IS NULL OR OLD.FPA_STATUS <> 'EMI')) THEN
    EXECUTE PROCEDURE PA_ENCOLAR_FACTURA(NEW.IDCOMPANIA, NEW.IDFACTURA);
END^

SET TERM ; ^

