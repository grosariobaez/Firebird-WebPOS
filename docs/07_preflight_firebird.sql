/* SOLO LECTURA. Ejecutar en JOMLIA y compartir salida SIN datos personales. */
SELECT RDB$GET_CONTEXT('SYSTEM','ENGINE_VERSION') AS VERSION_FIREBIRD FROM RDB$DATABASE;
-- Pago: tipos/status y volumetria para estudiar pagos mixtos.
SELECT FPA_TIPO,FPA_STATUS,COUNT(*) AS CANTIDAD
FROM FORMAS_PAGO
GROUP BY FPA_TIPO,FPA_STATUS
ORDER BY FPA_TIPO,FPA_STATUS;
-- Descuentos: observar semantica, sin sacar una conclusion automatica.
SELECT FIRST 20 IDCOMPANIA,IDFACTURA,SECUENCIA,DFC_CANTIDAD,
       DFC_PRECIO,DFC_DESCUENTO,DFC_ITBIS,ITBIS
FROM DET_FACTURA WHERE COALESCE(DFC_DESCUENTO,0)<>0
ORDER BY IDFACTURA DESC,SECUENCIA;
-- Ejemplos de medios de pago de ultimas facturas (anonimizar identificadores).
SELECT FIRST 40 P.IDCOMPANIA,P.IDFACTURA,P.FPA_SECUENCIA,
       P.FPA_TIPO,P.FPA_MONTO,P.FPA_STATUS,
       P.FPA_EFECTIVO,P.FPA_TARJETAMONTO,P.FPA_TRANSFERENCIA,
       P.FPA_CHEQUEMONTO,P.FPA_CREDITO,F.FAC_TOTAL,F.FAC_PAGADO
FROM FORMAS_PAGO P
JOIN FACTURAS F ON F.IDCOMPANIA=P.IDCOMPANIA AND F.IDFACTURA=P.IDFACTURA
WHERE P.FPA_STATUS='EMI'
ORDER BY P.IDFACTURA DESC,P.FPA_SECUENCIA;
