SELECT IDCOMPANIA, IDFACTURA, IDCLIENTE, FAC_FECHA, FAC_NOMBRE,
       FAC_DIRECCION1, FAC_DIRECCION2, FAC_ITBIS, FAC_TOTAL,
       FAC_PAGADO, FAC_DESCUENTO, FAC_STATUS, FAC_NCF,
       FAC_FECHAVENCE, FAC_TIPO, TIPONCF, NOMBRE_NCF,
       FAC_DEVUELTO, FAC_EFECTIVO, FAC_TARJETA, FAC_TRANSFER,
       FAC_CREDI
FROM FACTURAS
WHERE IDCOMPANIA=1 AND IDFACTURA=100;

SELECT SECUENCIA, IDPRODUCTO, DFC_REFERENCIA, DFC_BARRA,
       DFC_DESCRIPCION, DFC_CANTIDAD, DFC_PRECIO,
       DFC_DESCUENTO, DFC_ITBIS, DFC_STATUS, DFC_CANTDEVUELTA,
       ITBIS, MEDIDA
FROM DET_FACTURA
WHERE IDCOMPANIA=1 AND IDFACTURA=100
ORDER BY SECUENCIA;

SELECT FPA_SECUENCIA, FPA_TIPO, FPA_MONTO, FPA_STATUS,
       FPA_EFECTIVO, FPA_TARJETAMONTO, FPA_TRANSFERENCIA,
       FPA_CHEQUEMONTO, FPA_CREDITO, FPA_BANCO
FROM FORMAS_PAGO
WHERE IDCOMPANIA=1 AND IDFACTURA=100
ORDER BY FPA_SECUENCIA;

SELECT RDB$GET_CONTEXT('SYSTEM','ENGINE_VERSION') AS FIREBIRD_VERSION
FROM RDB$DATABASE;
