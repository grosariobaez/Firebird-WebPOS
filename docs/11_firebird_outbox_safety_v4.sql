CREATE TABLE PA_FB_EVENTOS (
  IDCOMPANIA INTEGER NOT NULL,
  IDFACTURA INTEGER NOT NULL,
  CODIGO VARCHAR(40) NOT NULL,
  FECHA_EVENTO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PROCESADO CHAR(1) DEFAULT 'N' NOT NULL,
  FECHA_PROCESADO TIMESTAMP,
  CONSTRAINT PK_PA_FB_EVENTOS PRIMARY KEY (IDCOMPANIA, IDFACTURA, CODIGO),
  CONSTRAINT CK_PA_FB_EVENTOS_PROC CHECK (PROCESADO IN ('N','S'))
);

CREATE INDEX IDX_PA_FB_EVENTOS_PEND ON PA_FB_EVENTOS (PROCESADO, FECHA_EVENTO);

SET TERM ^ ;

CREATE OR ALTER PROCEDURE PA_ENCOLAR_FACTURA (
  P_IDCOMPANIA INTEGER,
  P_IDFACTURA INTEGER
)
AS
  DECLARE VARIABLE V_ESTADO CHAR(1);
  DECLARE VARIABLE V_CODIGO VARCHAR(40);
BEGIN
  V_ESTADO = NULL;
  SELECT ESTADO FROM PA_FB_OUTBOX
   WHERE IDCOMPANIA = :P_IDCOMPANIA AND IDFACTURA = :P_IDFACTURA
   INTO :V_ESTADO;

  IF (V_ESTADO IS NULL) THEN
  BEGIN
    BEGIN
      INSERT INTO PA_FB_OUTBOX (
        IDCOMPANIA, IDFACTURA, ESTADO, INTENTOS,
        FECHA_EVENTO, FECHA_PROCESADO, PROXIMO_INTENTO, ULTIMO_ERROR
      ) VALUES (
        :P_IDCOMPANIA, :P_IDFACTURA, 'P', 0,
        CURRENT_TIMESTAMP, NULL, NULL, NULL
      );
      WHEN SQLCODE -803 DO V_ESTADO = V_ESTADO;
    END
  END
  ELSE
  BEGIN
    V_CODIGO = 'SOURCE_REQUEUE_' || V_ESTADO;
    BEGIN
      INSERT INTO PA_FB_EVENTOS (IDCOMPANIA, IDFACTURA, CODIGO, FECHA_EVENTO, PROCESADO)
      VALUES (:P_IDCOMPANIA, :P_IDFACTURA, :V_CODIGO, CURRENT_TIMESTAMP, 'N');
      WHEN SQLCODE -803 DO V_ESTADO = V_ESTADO;
    END
  END
END^

CREATE OR ALTER TRIGGER PA_TR_FACTURAS_ANU FOR FACTURAS
ACTIVE AFTER UPDATE POSITION 100
AS
  DECLARE VARIABLE V_ESTADO CHAR(1);
  DECLARE VARIABLE V_CODIGO VARCHAR(40);
BEGIN
  IF (NEW.FAC_STATUS = 'ANU' AND
      (OLD.FAC_STATUS IS NULL OR OLD.FAC_STATUS <> 'ANU')) THEN
  BEGIN
    V_ESTADO = NULL;
    SELECT ESTADO FROM PA_FB_OUTBOX
     WHERE IDCOMPANIA = NEW.IDCOMPANIA AND IDFACTURA = NEW.IDFACTURA
     INTO :V_ESTADO;

    IF (V_ESTADO = 'S') THEN
      V_CODIGO = 'POST_SYNC_CANCELLATION';
    ELSE IF (V_ESTADO = 'R') THEN
      V_CODIGO = 'ANU_DURING_PROCESSING';
    ELSE
      V_CODIGO = 'ANU_BEFORE_SYNC';

    BEGIN
      INSERT INTO PA_FB_EVENTOS (IDCOMPANIA, IDFACTURA, CODIGO, FECHA_EVENTO, PROCESADO)
      VALUES (NEW.IDCOMPANIA, NEW.IDFACTURA, :V_CODIGO, CURRENT_TIMESTAMP, 'N');
      WHEN SQLCODE -803 DO V_ESTADO = V_ESTADO;
    END
  END
END^

SET TERM ; ^

