-- Tipos de pago y estados observados
SELECT FPA_TIPO, FPA_STATUS, COUNT(*) AS REGISTROS
FROM FORMAS_PAGO
GROUP BY FPA_TIPO, FPA_STATUS
ORDER BY FPA_TIPO, FPA_STATUS;

-- Impuesto/clase de linea: los campos locales no prueban la equivalencia 0..4 WebPOS.
SELECT ITBIS, COUNT(*) AS REGISTROS
FROM DET_FACTURA
GROUP BY ITBIS ORDER BY REGISTROS DESC;

-- Montos agregados de impuestos y descuentos: muestrear facturas para conciliacion.
SELECT FIRST 30
  F.IDCOMPANIA, F.IDFACTURA, F.FAC_FECHA, F.FAC_NCF,
  F.FAC_TOTAL, F.FAC_ITBIS, F.FAC_DESCUENTO,
  (SELECT SUM(D.DFC_CANTIDAD * D.DFC_PRECIO)
   FROM DET_FACTURA D WHERE D.IDCOMPANIA=F.IDCOMPANIA
     AND D.IDFACTURA=F.IDFACTURA) AS LINEAS_BRUTO,
  (SELECT SUM(D.DFC_DESCUENTO)
   FROM DET_FACTURA D WHERE D.IDCOMPANIA=F.IDCOMPANIA
     AND D.IDFACTURA=F.IDFACTURA) AS LINEAS_DESCUENTO,
  (SELECT SUM(P.FPA_MONTO)
   FROM FORMAS_PAGO P WHERE P.IDCOMPANIA=F.IDCOMPANIA
     AND P.IDFACTURA=F.IDFACTURA) AS SUMA_PAGOS
FROM FACTURAS F
WHERE F.FAC_NCF IS NOT NULL
ORDER BY F.FAC_FECHA DESC;

-- Metadatos de tabla CLIENTES (si existe):
SELECT RF.RDB$FIELD_NAME AS CAMPO
FROM RDB$RELATION_FIELDS RF
WHERE RF.RDB$RELATION_NAME='CLIENTES'
ORDER BY RF.RDB$FIELD_POSITION;
